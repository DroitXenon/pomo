"""Convert your own GIF or video into the robot's video page.

Writes include/video_user.h (baseline JPEG frames sized to fit 320x240), which
is gitignored: the frames stay on your machine and on the robot, never in the
repository. Without that file the robot plays its original built-in animation.
You are responsible for having the right to use the video you load.

    python firmware/robot-adapter/tools/make_video.py clip.gif --title "My clip"
    python firmware/robot-adapter/tools/make_video.py clip.mp4 --seconds 15 --audio   # also load its soundtrack
    python firmware/robot-adapter/tools/make_video.py --remove                        # back to the animation

--audio also writes include/music_user.h from the same file (as make_music.py
does), played with the video. Then upload: pio run -t upload. Needs ffmpeg.
"""

import argparse
from pathlib import Path
import shutil
import struct
import subprocess
import sys
import tempfile

TOOLS = Path(__file__).resolve().parent
sys.path.insert(0, str(TOOLS))
import make_music  # noqa: E402

OUTPUT = TOOLS.parent / "include" / "video_user.h"
SCREEN = (320, 240)
MAX_SECONDS = 30
MAX_BYTES = 4_000_000  # Leaves room for audio in the 6.5 MB app partition.


def jpeg_size(data):
    """Return (width, height) from a JPEG's start-of-frame marker."""
    i = 2
    while i + 9 < len(data):
        if data[i] != 0xFF:
            i += 1
            continue
        marker, length = data[i + 1], struct.unpack(">H", data[i + 2:i + 4])[0]
        if marker in (0xC0, 0xC1, 0xC2):
            height, width = struct.unpack(">HH", data[i + 5:i + 9])
            return width, height
        i += 2 + length
    raise ValueError("no JPEG frame header")


def extract_frames(source, folder, fps, seconds, quality):
    if not shutil.which("ffmpeg"):
        sys.exit("Install ffmpeg (brew install ffmpeg) to convert video.")
    width, height = SCREEN
    subprocess.run([
        "ffmpeg", "-nostdin", "-loglevel", "error", "-y", "-i", str(source), "-t", str(seconds),
        "-vf", f"fps={fps},scale={width}:{height}:force_original_aspect_ratio=decrease:flags=area,"
               "scale=trunc(iw/2)*2:trunc(ih/2)*2,format=yuvj420p",
        "-c:v", "mjpeg", "-q:v", str(quality), str(folder / "frame%04d.jpg"),
    ], check=True)
    return [path.read_bytes() for path in sorted(folder.glob("frame*.jpg"))]


def write_header(frames, title, fps, with_audio):
    width, height = jpeg_size(frames[0])
    offsets, total = [0], 0
    for frame in frames:
        total += len(frame)
        offsets.append(total)
    data = b"".join(frames)
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    lines = [
        "// Generated by tools/make_video.py from your own video; gitignored, do not commit.",
        "#pragma once", "#include <Arduino.h>", "",
        f'#define USER_VIDEO_TITLE "{title}"',
        f"#define USER_VIDEO_FPS {fps}u",
        f"#define USER_VIDEO_FRAMES {len(frames)}u",
        f"#define USER_VIDEO_WIDTH {width}",
        f"#define USER_VIDEO_HEIGHT {height}",
    ]
    if with_audio:
        lines.append("#define USER_VIDEO_WITH_AUDIO 1")
    lines += [
        f"const uint32_t USER_VIDEO_OFFSETS[{len(offsets)}] = {{{', '.join(map(str, offsets))}}};",
        f"const uint8_t USER_VIDEO_DATA[{len(data)}] PROGMEM = {{\n  " + ",\n  ".join(rows) + "\n};", "",
    ]
    OUTPUT.write_text("\n".join(lines))
    return width, height, len(data)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("video", nargs="?", type=Path, help="GIF, MP4, MOV, ... file")
    parser.add_argument("--title", help="title shown on the robot (default: file name)")
    parser.add_argument("--seconds", type=float, default=15, help=f"at most this many seconds (max {MAX_SECONDS})")
    parser.add_argument("--fps", type=int, default=10, help="frames per second, 1 to 15 (default 10)")
    parser.add_argument("--quality", type=int, default=6, help="JPEG quality 2 (best) to 31 (smallest), default 6")
    parser.add_argument("--audio", action="store_true", help="also load the file's soundtrack as music_user.h")
    parser.add_argument("--remove", action="store_true", help="delete video_user.h and use the built-in animation")
    args = parser.parse_args()
    if args.remove:
        OUTPUT.unlink(missing_ok=True)
        print("removed include/video_user.h; the robot will play the built-in animation")
        print("(music_user.h, if any, is unchanged; use make_music.py --remove for that)")
        return
    if args.video is None or not args.video.is_file():
        parser.error("give a video or GIF file (or --remove)")
    if not 1 <= args.seconds <= MAX_SECONDS:
        parser.error(f"--seconds must be between 1 and {MAX_SECONDS}")
    if not 1 <= args.fps <= 15:
        parser.error("--fps must be between 1 and 15")
    if not 2 <= args.quality <= 31:
        parser.error("--quality must be between 2 and 31")
    with tempfile.TemporaryDirectory() as tmp:
        frames = extract_frames(args.video, Path(tmp), args.fps, args.seconds, args.quality)
        if not frames:
            sys.exit("ffmpeg produced no frames")
        size = sum(map(len, frames))
        if size > MAX_BYTES:
            sys.exit(f"{size / 1e6:.1f} MB of frames is over the {MAX_BYTES / 1e6:.0f} MB limit; "
                     "use fewer --seconds, a lower --fps or a higher --quality number")
        if args.audio:
            converted = Path(tmp) / "audio.wav"
            make_music.convert(args.video, converted, args.seconds)
            audio, length_ms = make_music.canonical_wav(converted, args.seconds)
            make_music.write_header(audio, make_music.c_title(args.title or args.video.stem), length_ms)
    title = make_music.c_title(args.title or args.video.stem)
    width, height, size = write_header(frames, title, args.fps, args.audio)
    print(f'wrote include/video_user.h: "{title}", {len(frames)} frames at {args.fps} fps, '
          f"{width}x{height}, {size / 1e6:.2f} MB" + (" + soundtrack in music_user.h" if args.audio else ""))
    print("now upload: cd firmware/robot-adapter && pio run -t upload")


if __name__ == "__main__":
    main()
