"""Convert your own audio file into the robot's music page.

Writes include/music_user.h (16 kHz, 16-bit mono WAV), which is gitignored:
the audio stays on your machine and on the robot, never in the repository.
Without that file the robot plays the original tune in include/music_tune.h.
You are responsible for having the right to use the audio you load.

    python firmware/robot-adapter/tools/make_music.py song.mp3 --title "My song"
    python firmware/robot-adapter/tools/make_music.py --remove     # back to the tune

Then upload the firmware (pio run -t upload in firmware/robot-adapter).
Uses ffmpeg when installed (any format it reads), otherwise macOS afconvert.
"""

import argparse
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
import wave

OUTPUT = Path(__file__).resolve().parents[1] / "include" / "music_user.h"
RATE = 16000
MAX_SECONDS = 180  # About 5.8 MB of flash; the app partition holds 6.5 MB.


def convert(source, target, seconds):
    if shutil.which("ffmpeg"):
        command = ["ffmpeg", "-nostdin", "-loglevel", "error", "-y", "-i", str(source),
                   "-t", str(seconds), "-ac", "1", "-ar", str(RATE), "-sample_fmt", "s16",
                   "-map_metadata", "-1", "-f", "wav", str(target)]
    elif shutil.which("afconvert"):
        command = ["afconvert", "-f", "WAVE", "-d", f"LEI16@{RATE}", "-c", "1",
                   str(source), str(target)]
    else:
        sys.exit("Install ffmpeg (or use macOS afconvert) to convert audio.")
    subprocess.run(command, check=True)


def canonical_wav(path, seconds):
    """Re-write as a plain 44-byte-header WAV, trimmed to the time limit."""
    with wave.open(str(path), "rb") as source:
        params = source.getparams()
        if (params.nchannels, params.sampwidth, params.framerate) != (1, 2, RATE):
            sys.exit(f"unexpected converted format: {params}")
        frames = source.readframes(min(source.getnframes(), int(seconds * RATE)))
    plain = path.with_name("plain.wav")
    with wave.open(str(plain), "wb") as target:
        target.setparams(params)
        target.writeframes(frames)
    return plain.read_bytes(), len(frames) // 2 * 1000 // RATE


def c_title(text):
    text = re.sub(r"[^ !#-\[\]-~]", "", text).strip()[:24] or "My music"
    return text


def write_header(data, title, length_ms):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    OUTPUT.write_text(
        "// Generated by tools/make_music.py from your own audio; gitignored, do not commit.\n"
        "#pragma once\n#include <Arduino.h>\n\n"
        f'#define USER_MUSIC_TITLE "{title}"\n'
        f"#define USER_MUSIC_MS {length_ms}u\n"
        f"const uint8_t USER_MUSIC[{len(data)}] PROGMEM = {{\n  " + ",\n  ".join(rows) + "\n};\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("audio", nargs="?", type=Path, help="WAV, MP3, M4A, ... file")
    parser.add_argument("--title", help="title shown on the robot (default: file name)")
    parser.add_argument("--seconds", type=float, default=60,
                        help=f"keep at most this many seconds (default 60, max {MAX_SECONDS})")
    parser.add_argument("--remove", action="store_true", help="delete music_user.h and use the tune")
    args = parser.parse_args()
    if args.remove:
        OUTPUT.unlink(missing_ok=True)
        print("removed include/music_user.h; the robot will play the built-in tune")
        return
    if args.audio is None or not args.audio.is_file():
        parser.error("give an audio file (or --remove)")
    if not 1 <= args.seconds <= MAX_SECONDS:
        parser.error(f"--seconds must be between 1 and {MAX_SECONDS}")
    with tempfile.TemporaryDirectory() as tmp:
        converted = Path(tmp) / "converted.wav"
        convert(args.audio, converted, args.seconds)
        data, length_ms = canonical_wav(converted, args.seconds)
    title = c_title(args.title or args.audio.stem)
    write_header(data, title, length_ms)
    print(f'wrote include/music_user.h: "{title}", {length_ms / 1000:.1f} s, {len(data) / 1e6:.2f} MB')
    print("now upload: cd firmware/robot-adapter && pio run -t upload")


if __name__ == "__main__":
    main()
