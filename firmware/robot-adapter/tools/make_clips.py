"""Record the reminder sentences as WAV clips and embed them in the firmware.

macOS only (uses `say` and `afconvert`). Run from the repository root after
changing REMINDER_MESSAGES in backend/policy.py:

    conda run --name pomo python firmware/robot-adapter/tools/make_clips.py
    conda run --name pomo python firmware/robot-adapter/tools/make_clips.py --voice "Daniel (English (UK))"

The text comes from backend/policy.py, so the robot says exactly what the
simulator shows. The output is include/clips.h (16 kHz, 16-bit mono WAV).
"""

import argparse
from pathlib import Path
import subprocess
import sys
import tempfile
import wave

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
from backend.policy import REMINDER_MESSAGES  # noqa: E402

OUTPUT = Path(__file__).resolve().parents[1] / "include" / "clips.h"


def record(text, voice, rate, folder, name):
    aiff = folder / f"{name}.aiff"
    wav = folder / f"{name}.wav"
    subprocess.run(["say", "-v", voice, "-r", str(rate), "-o", str(aiff), text], check=True)
    subprocess.run(["afconvert", "-f", "WAVE", "-d", "LEI16@16000", "-c", "1",
                    str(aiff), str(wav)], check=True)
    # Rewrite as a canonical 44-byte-header WAV (afconvert adds a padding chunk).
    with wave.open(str(wav), "rb") as source:
        params, frames = source.getparams(), source.readframes(source.getnframes())
    plain = folder / f"{name}-plain.wav"
    with wave.open(str(plain), "wb") as target:
        target.setparams(params)
        target.writeframes(frames)
    return plain.read_bytes()


def c_array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    body = ",\n  ".join(rows)
    return f"const uint8_t {name}[{len(data)}] PROGMEM = {{\n  {body}\n}};\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--voice", default="Flo (English (UK))")
    parser.add_argument("--rate", type=int, default=165, help="words per minute")
    args = parser.parse_args()
    parts = [
        "// Generated by tools/make_clips.py; do not edit by hand.\n",
        f"// Voice: {args.voice}, {args.rate} wpm, 16 kHz 16-bit mono WAV.\n",
        "#pragma once\n#include <Arduino.h>\n\n",
    ]
    with tempfile.TemporaryDirectory() as tmp:
        for stage in sorted(REMINDER_MESSAGES):
            text = REMINDER_MESSAGES[stage]
            data = record(text, args.voice, args.rate, Path(tmp), f"stage{stage}")
            parts.append(f"// Stage {stage}: {text}\n")
            parts.append(c_array(f"REMINDER_CLIP_{stage}", data) + "\n")
            print(f"stage {stage}: {len(data)} bytes, {(len(data) - 44) / 32000:.1f} s")
    OUTPUT.write_text("".join(parts))
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
